#!/usr/bin/env python3
"""Build every poster page and the poster tiles on the home page.

Source of truth: one file per poster, posters/<slug>/poster.json (plus its PDF and any other files
in the same folder). Run after adding or editing a poster:

    python scripts/build_posters.py            # write p/<slug>/index.html and the tile list in index.html
    python scripts/build_posters.py --check    # exit 1 if generated files are out of date (no writes)

Generated: p/<slug>/index.html (what the QR codes open), posters/index.html (all posters, with search), and
the newest few posters plus an "all posters" button on the home page (how many: "home_poster_limit" in site.json). Do not edit them by hand: edit
poster.json and re-run this script. Standard library only.

poster.json fields
  title            required  poster title (shown at the top of the poster page)
  conference       required  where it was presented
  date             optional  "2026-04-18", "2026-04" or "2026" (anything else is shown as typed; may be left out)
  pdf              optional  poster PDF in the same folder (default "poster.pdf" if that file exists;
                             with no PDF the page simply has no poster buttons yet)
  authors          optional  author line
  affiliation      optional  affiliation line under the authors (a string, or a list: one line each)
  abstract         optional  abstract text shown on the page: a string, or a list of paragraphs
                             (a leading "Background:", "Methods:", "Results:" or "Conclusions:" is bolded)
  abstract_url     optional  link to the abstract (https://... or a file in the poster's folder)
  references       optional  list of reference strings (URLs and "doi:10...." become links)
  references_pdf   optional  standalone references document in the poster's folder, or a URL
  preview          optional  preview image of the poster (jpg/png) in the poster's folder
  links            optional  extra buttons: [{"label": "Related paper", "url": "/#pub-rivas-2025"}]
  keywords         optional  extra words that only the search box looks at
"""
import argparse
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = json.loads((ROOT / "site.json").read_text(encoding="utf-8"))
SLUG_RE = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August",
          "September", "October", "November", "December"]
TILES_RE = re.compile(r"(<!-- POSTERS:START[^>]*-->)(.*?)(<!-- POSTERS:END -->)", re.S)
GENERATED_ARCHIVE_MARK = "<!-- generated by scripts/build_posters.py; edit posters/<slug>/poster.json instead -->"
GENERATED_MARK ="<!-- generated by scripts/build_posters.py; edit posters/{slug}/poster.json instead -->"

