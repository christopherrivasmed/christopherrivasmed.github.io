def load_items(kind):
    cfg = KINDS[kind]
    items, errors = [], []
    for jf in sorted((ROOT / cfg["data"]).glob(f"*/{cfg['json']}")):
        slug = jf.parent.name
        where = f"{cfg['data']}/{slug}/{cfg['json']}"
        if not SLUG_RE.fullmatch(slug):
            errors.append(f"{cfg['data']}/{slug}: folder name must be lowercase letters, digits and hyphens")
            continue
        try:
            data = json.loads(jf.read_text(encoding="utf-8"))
        except json.JSONDecodeError as e:
            errors.append(f"{where}: invalid JSON ({e})")
            continue
        venue_key = "conference" if kind == "poster" else "venue"
        for key in ("title", venue_key):
            if not str(data.get(key, "")).strip():
                errors.append(f"{where}: missing '{key}'")
        data["venue"] = data.get(venue_key, "")
        data["kind"], data["slug"], data["_dir"] = kind, slug, jf.parent

        def need_file(field, val):
            if val and not re.match(r"https?://", val) and not (jf.parent / val).is_file():
                errors.append(f"{where}: file '{val}' (field '{field}') not found in {cfg['data']}/{slug}/")

        if kind == "poster":
            if "pdf" not in data and (jf.parent / "poster.pdf").is_file():
                data["pdf"] = "poster.pdf"
            for key in ("pdf", "references_pdf", "preview", "abstract_url"):
                need_file(key, data.get(key, ""))
        else:
            for key in ("slides", "references_pdf"):
                need_file(key, data.get(key, ""))
            vid = data.get("video")
            if vid:
                if not re.fullmatch(r"[A-Za-z0-9_-]{11}", vid.get("youtube_id", "")):
                    errors.append(f"{where}: video.youtube_id must be the 11-character video id")
                if not vid.get("thumbnail"):
                    errors.append(f"{where}: video.thumbnail (a file in the talk's folder) is required")
                need_file("video.thumbnail", vid.get("thumbnail", ""))
            last = -1
            for ch in data.get("chapters", []):
                if not re.fullmatch(r"\d{1,2}(:\d{2}){1,2}", ch.get("time", "")) or not ch.get("title"):
                    errors.append(f"{where}: bad chapter {ch!r} (need \"time\": \"m:ss\" and \"title\")")
                    continue
                if to_seconds(ch["time"]) <= last:
                    errors.append(f"{where}: chapter times must be in increasing order ({ch['time']})")
                last = to_seconds(ch["time"])
        data["_sort"], data["_date_display"], data["_date_iso"] = parse_date(data.get("date", ""))
        items.append(data)
    return items, errors


def newest_first(items):
    dated = sorted([i for i in items if i["_sort"]], key=lambda i: i["_sort"], reverse=True)
    return dated + [i for i in items if not i["_sort"]]


# ----------------------------------------------------------------------------- helpers

def file_href(item, value):
    """URL (from a page two folders deep) for a field that is https://... or a file in the item's folder."""
    if re.match(r"https?://", value):
        return value
    return f"../../{KINDS[item['kind']]['data']}/{item['slug']}/{value}"


def extra_href(url):
    if url.startswith("#"):
        return "../../" + url
    if url.startswith("/"):
        return "../.." + url
    return url


def show_date(item):
    """Hide a year-only date when the venue name already contains it (e.g. 'Discovery Day 2026')."""
    d = item["_date_display"]
    if not d:
        return False
    return not (re.fullmatch(r"\d{4}", d) and d in item["venue"])


def contents(item):
    """What the page actually offers, e.g. 'Poster and abstract' (mentions references only if present)."""
    parts = []
    if item["kind"] == "poster":
        if item.get("pdf"):
            parts.append("poster")
        if item.get("abstract") or item.get("abstract_url"):
            parts.append("abstract")
    else:
        if item.get("video"):
            parts.append("video")
            if item.get("chapters"):
                parts.append("chapters")
        if item.get("slides"):
            parts.append("slides")
        if not parts and item.get("background"):
            parts.append("summary")
    if item.get("references") or item.get("references_pdf"):
        parts.append("references")
    if not parts:
        return "Details"
    text = ", ".join(parts[:-1]) + (" and " if len(parts) > 1 else "") + parts[-1]
    return text[0].upper() + text[1:]


def file_button(item, value, label, icon_name=None):
    """Button for a field that is a web link or a file in the item's folder (files show type and size)."""
    href = file_href(item, value)
    if re.match(r"https?://", value):
        return f'<li><a class="btn" href="{esc(href)}">{icon(icon_name or "link")}{label}</a></li>'
    f = item["_dir"] / value
    kind = f.suffix.lstrip(".").upper() or "file"
    size = f", {human_size(f)}" if f.is_file() else ""
    return (f'<li><a class="btn" href="{esc(href)}" target="_blank" rel="noopener">'
            f'{icon(icon_name or "doc")}{label} ({kind}{size})</a></li>')


def paragraphs(text, indent="      "):
    """Paragraphs from a string or list; a leading section name such as 'Methods:' is bolded."""
    out = []
    for para in text if isinstance(text, list) else [text]:
        m = re.match(r"(Background and Aims?|Background|Introduction|Objectives?|Purpose|Methods|Results|Conclusions?|Discussion):\s+", para)
        if m:
            out.append(f"{indent}<p><strong>{esc(m.group(1))}:</strong> {esc(para[m.end():])}</p>")
        else:
            out.append(f"{indent}<p>{esc(para)}</p>")
    return "\n".join(out)


def references_section(item):
    refs = item.get("references", [])
    if not (refs or item.get("references_pdf")):
        return ""
    items = "\n".join(f"        <li>{linkify(r)}</li>" for r in refs)
    lst = f'      <ol class="refs">\n{items}\n      </ol>' if refs else ""
    dl = (f'\n      <p><a class="btn" href="{file_href(item, item["references_pdf"])}">'
          f'{icon("download")}Download references (PDF)</a></p>' if item.get("references_pdf") else "")
    return f'''    <section id="references" aria-labelledby="references-h">
      <h2 id="references-h">References</h2>
{lst}{dl}
    </section>'''


def goat_snippet():
    code = SITE.get("goatcounter_code")
    if not code:
        return ""
    return (f'  <script data-goatcounter="https://{esc(code)}.goatcounter.com/count"\n'
            f'          async src="https://gc.zgo.at/count.js"></script>\n')


