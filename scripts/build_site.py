# ----------------------------------------------------------------------------- item pages

def meta_lines(item):
    date_el = (f'<time datetime="{item["_date_iso"]}">{esc(item["_date_display"])}</time>'
               if item["_date_iso"] else esc(item["_date_display"]))
    return f"<strong>{esc(item['venue'])}</strong>" + (f" &middot; {date_el}" if show_date(item) else "")


def link_buttons(item):
    return [f'<li><a class="btn" href="{esc(extra_href(ln["url"]))}">{icon("link")}{esc(ln["label"])}</a></li>'
            for ln in item.get("links", [])]


def actions_block(buttons):
    return ('\n    <ul class="btn-grid actions">\n' + "\n".join("      " + b for b in buttons) + "\n    </ul>\n") if buttons else ""


def poster_page(p):
    base = SITE["base_url"].rstrip("/")
    slug, title = p["slug"], p["title"]
    when = f", {p['_date_display']}" if show_date(p) else ""
    desc = f"{p['venue']}{when}. {contents(p)} by {SITE['name']}."
    og_img = f"{base}/assets/og-image.png"
    if p.get("preview") and not re.match(r"https?://", p["preview"]):
        og_img = f"{base}/posters/{slug}/{p['preview']}"

    buttons, pdf_href = [], ""
    if p.get("pdf"):
        pdf = p["_dir"] / p["pdf"]
        pdf_href = file_href(p, p["pdf"])
        label = f"View poster (PDF, {human_size(pdf)})" if pdf.is_file() else "View poster (PDF)"
        buttons.append(f'<li><a class="btn btn-primary" href="{pdf_href}" target="_blank" rel="noopener">{icon("doc")}{label}</a></li>')
        buttons.append(f'<li><a class="btn" href="{pdf_href}" download>{icon("download")}Download poster</a></li>')
    if p.get("abstract_url"):
        buttons.append(file_button(p, p["abstract_url"], "Abstract"))
    if p.get("references_pdf"):
        buttons.append(file_button(p, p["references_pdf"], "References", icon_name="list"))
    buttons += link_buttons(p)

    body = []
    if p.get("preview"):
        img = f'<img src="{file_href(p, p["preview"])}" alt="Preview of the poster: {esc(title)}">'
        body.append(f'    <a class="poster-preview" href="{pdf_href}" target="_blank" rel="noopener">{img}</a>' if pdf_href
                    else f'    <div class="poster-preview">{img}</div>')
    if p.get("abstract"):
        body.append(f'''    <section id="abstract" aria-labelledby="abstract-h">
      <h2 id="abstract-h">Abstract</h2>
{paragraphs(p["abstract"])}
    </section>''')
    refs = references_section(p)
    if refs:
        body.append(refs)

    authors = f'\n    <p class="authors">{esc(p["authors"])}</p>' if p.get("authors") else ""
    if p.get("affiliation"):
        affs = p["affiliation"] if isinstance(p["affiliation"], list) else [p["affiliation"]]
        authors += '\n    <p class="affiliation">' + "<br>".join(esc(a) for a in affs) + "</p>"

    return f"""{head(f"{title} | {SITE['name']}", desc, f"{base}/p/{slug}/", "article", og_img, "../../", f"posters/{slug}/poster.json")}
<body>
  <a class="skip-link" href="#main">Skip to content</a>

  <header class="wrap poster-top">
    <a class="back" href="../../presentations/">{icon("back")}All presentations</a>
  </header>

  <main id="main" class="wrap poster-page">
    <h1>{esc(title)}</h1>
    <p class="conf">{meta_lines(p)}</p>{authors}
{actions_block(buttons)}
{chr(10).join(body)}
  </main>

{footer("../../")}
</body>
</html>
"""


def talk_page(t):
    base = SITE["base_url"].rstrip("/")
    slug, title = t["slug"], t["title"]
    vid = t.get("video")
    when = f", {t['_date_display']}" if show_date(t) else ""
    desc = f"{t['venue']}{when}. {contents(t)} presented by {SITE['name']}."
    og_img = f"{base}/assets/og-image.png"
    if vid:
        og_img = f"{base}/talks/{slug}/{vid['thumbnail']}"

    body = []
    if t.get("background"):
        body.append(f'''    <section id="about-talk" aria-labelledby="about-talk-h">
      <h2 id="about-talk-h">About this talk</h2>
{paragraphs(t["background"])}
    </section>''')

    if vid:
        vid_id = vid["youtube_id"]
        watch = f"https://www.youtube.com/watch?v={vid_id}"
        dur = f" ({esc(vid['duration'])})" if vid.get("duration") else ""
        thumb = file_href(t, vid["thumbnail"])
