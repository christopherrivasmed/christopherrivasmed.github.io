# ----------------------------------------------------------------------------- tiles and lists

def tile(item, prefix="", level=3, show_kind=False):
    """One tile. prefix is the path from the page to the site root ('' on the home page, '../' in presentations/)."""
    cfg = KINDS[item["kind"]]
    search = " ".join([item["title"], item["venue"], item["_date_display"], str(item.get("date", "")),
                       item.get("authors", "") or item.get("presenter", ""), " ".join(item.get("keywords", [])),
                       item["slug"], cfg["label"]])
    date_html = f' &middot; {esc(item["_date_display"])}' if show_date(item) else ""
    kind_html = f'          <span class="tile-kind">{cfg["label"]}</span>\n' if show_kind else ""
    return f"""      <li data-kind="{item['kind']}" data-search="{esc(search)}">
        <a class="tile" href="{prefix}{cfg['page']}/{item['slug']}/">
{kind_html}          <h{level} class="tile-title">{esc(item['title'])}</h{level}>
          <p class="tile-meta">{esc(item['venue'])}{date_html}</p>
          <p class="tile-cta">{contents(item)} {icon('chevron')}</p>
        </a>
      </li>
"""


def home_block(talks, posters):
    """Newest few talks and posters (grouped) plus the 'all' button, for the home page."""
    total = len(talks) + len(posters)
    if not total:
        return "\n      <p>Talks and posters coming soon.</p>\n      "
    groups = []
    for kind, items, key, default in (("talk", talks, "home_talk_limit", 2), ("poster", posters, "home_poster_limit", 2)):
        shown = items[:int(SITE.get(key, default))]
        if shown:
            groups.append(f'\n      <h3 class="group-h">{KINDS[kind]["group"]}</h3>\n      <ul class="tile-list">\n'
                          + "".join(tile(i, level=4) for i in shown) + "      </ul>")
    return ("".join(groups) + f'\n      <p class="more"><a class="btn more-btn" href="presentations/">'
            f'View all talks and presentations ({total}) {icon("chevron")}</a></p>\n      ')


