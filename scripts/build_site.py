def build():
    """Return ({path: new_text}, counts, errors, warnings)."""
    posters, e1 = load_items("poster")
    talks, e2 = load_items("talk")
    errors = e1 + e2
    posters, talks = newest_first(posters), newest_first(talks)
    for s in sorted({p["slug"] for p in posters} & {t["slug"] for t in talks}):
        errors.append(f"'{s}' is used by both a poster and a talk; slugs must be unique (QR codes look them up by slug)")

    outputs = {}
    for p in posters:
        outputs[ROOT / "p" / p["slug"] / "index.html"] = poster_page(p)
    for t in talks:
        outputs[ROOT / "t" / t["slug"] / "index.html"] = talk_page(t)
    outputs[ROOT / "presentations" / "index.html"] = archive_page(talks, posters)

    index_path = ROOT / "index.html"
    index = index_path.read_text(encoding="utf-8")
    if not HOME_RE.search(index):
        errors.append("index.html: PRESENTATIONS:START / PRESENTATIONS:END markers not found")
    else:
        outputs[index_path] = HOME_RE.sub(lambda m: m.group(1) + home_block(talks, posters) + m.group(3), index)

    warnings = []
    for kind, items in (("poster", posters), ("talk", talks)):
        cfg, slugs = KINDS[kind], {i["slug"] for i in items}
        pages = ROOT / cfg["page"]
        for d in sorted(pages.glob("*")) if pages.is_dir() else []:
            if d.is_dir() and d.name not in slugs:
                warnings.append(f"{cfg['page']}/{d.name}/ has no {cfg['data']}/{d.name}/{cfg['json']} (stale page? delete the folder if so)")
    return outputs, (len(talks), len(posters)), errors, warnings


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if generated files are stale")
    args = ap.parse_args()

    outputs, (n_talks, n_posters), errors, warnings = build()
    for w in warnings:
        print("warning:", w)
    if errors:
        for e in errors:
            print("error:", e)
        return 1

    stale = [path for path, text in outputs.items()
             if not path.exists() or path.read_text(encoding="utf-8") != text]
    summary = f"{n_talks} talk(s), {n_posters} poster(s)"
    if args.check:
        for path in stale:
            print("out of date:", path.relative_to(ROOT))
        print(f"{summary}, {len(stale)} generated file(s) out of date")
        return 1 if stale else 0

    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(outputs[path], encoding="utf-8", newline="\n")
        print("wrote", path.relative_to(ROOT))
    print(f"{summary}; {len(stale)} file(s) updated, {len(outputs) - len(stale)} unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
