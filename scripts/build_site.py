def icon(name):
    return f'<svg viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d="{ICONS[name]}"/></svg>'


def esc(s):
    return html.escape(str(s), quote=True)


def parse_date(raw):
    """Return (sort_key, display, iso_or_None)."""
    m = re.fullmatch(r"\s*(\d{4})(?:-(\d{2}))?(?:-(\d{2}))?\s*", str(raw))
    if not m:
        return ("", str(raw), None)
    y, mo, d = m.group(1), m.group(2), m.group(3)
    if mo and 1 <= int(mo) <= 12:
        if d:
            return (f"{y}-{mo}-{d}", f"{MONTHS[int(mo) - 1]} {int(d)}, {y}", f"{y}-{mo}-{d}")
        return (f"{y}-{mo}-00", f"{MONTHS[int(mo) - 1]} {y}", f"{y}-{mo}")
    return (f"{y}-00-00", y, y)


def human_size(path):
    n = path.stat().st_size
    return f"{n / 1024 / 1024:.1f} MB" if n >= 1024 * 1024 else f"{max(1, round(n / 1024))} KB"


def to_seconds(stamp):
    parts = [int(x) for x in stamp.split(":")]
    h, m, s = ([0] * (3 - len(parts))) + parts
    return h * 3600 + m * 60 + s


def linkify(text):
    """Escape text, turn *word* into italics (journal names, AMA style) and URLs / doi:10.x/y into links."""
    safe = re.sub(r"\*([^*\n]+)\*", r"<em>\1</em>", esc(text))

    def repl(m):
        url = m.group(0)
        trail = ""
        while url and url[-1] in ".,;:)" and not url.endswith("&amp;"):
            trail = url[-1] + trail
            url = url[:-1]
        if url.lower().startswith("doi:"):
            doi = url[4:].strip()
            href = "https://doi.org/" + doi
        else:
            href = url
        return f'<a href="{href}" rel="noopener">{url}</a>{trail}'

    return re.sub(r"https?://[^\s<]+|doi:\s*10\.\d{4,9}/[^\s<]+", repl, safe, flags=re.I)


