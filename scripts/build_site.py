#!/usr/bin/env python3
"""Build the poster pages, talk pages, the all-presentations page and the home-page list.

Source of truth: one folder per item, holding a JSON file and its files:

    posters/<slug>/poster.json   (+ poster.pdf, abstract.pdf, preview.jpg ...)  ->  p/<slug>/index.html
    talks/<slug>/talk.json       (+ thumb.jpg, slides.pdf ...)                  ->  t/<slug>/index.html

Run after adding or editing anything:

    python scripts/build_site.py            # write the generated pages
    python scripts/build_site.py --check    # exit 1 if generated files are out of date (no writes)

Generated (do not edit by hand; edit the JSON and re-run): p/<slug>/index.html and t/<slug>/index.html (what
QR codes open), presentations/index.html (every talk and poster, with filters and search), and the
"Talks and Presentations" list on the home page (between the PRESENTATIONS:START/END markers in index.html;
how many show: "home_talk_limit" and "home_poster_limit" in site.json). Standard library only.

poster.json fields
  title            required  poster title (shown at the top of the poster page)
  conference       required  where it was presented
  date             optional  "2026-04-18", "2026-04" or "2026" (anything else is shown as typed; may be left out)
  pdf              optional  poster PDF in the same folder (default "poster.pdf" if that file exists;
                             with no PDF the page simply has no poster buttons yet)
  authors          optional  author line
  affiliation      optional  affiliation line under the authors (a string, or a list: one line each)
  abstract         optional  abstract text shown on the page: a string, or a list of paragraphs
                             (a leading "Background:", "Methods:", "Results:" or "Conclusions:" is bolded)
  abstract_url     optional  link to the abstract (https://... or a file in the poster's folder)
  references       optional  list of reference strings (URLs and "doi:10...." become links; *text* is italic)
  references_pdf   optional  standalone references document in the poster's folder, or a URL
  preview          optional  preview image of the poster (jpg/png) in the poster's folder
  links            optional  extra buttons: [{"label": "Related paper", "url": "/#pub-rivas-2025"}]
  keywords         optional  extra words that only the search box looks at

talk.json fields
  title            required  talk title
  venue            required  where / for whom it was given
  date             optional  same formats as for posters
  presenter        optional  e.g. "Christopher A. Rivas" (shown as "Presented by ...")
  background       optional  text for the "About this talk" section: a string, or a list of paragraphs
  video            optional  {"youtube_id": "rfDcBr90m1U", "thumbnail": "thumb.jpg", "duration": "53:17",
                              "credit": "Global Neurosciences Institute"}; the thumbnail is a file in the
                              talk's folder, so the page makes no YouTube request until play is tapped
  chapters         optional  [{"time": "2:37", "title": "Meet the Researcher"}, ...]; each one starts the
                             video at that time
  slides           optional  slides PDF in the talk's folder, or a URL
  references, references_pdf, links, keywords   as for posters
"""
